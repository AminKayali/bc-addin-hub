// Builds CATALOG.md and catalog.json from addins/*/addin.json.
// Usage: node scripts/build-catalog.mjs [--check]
//   --check  fails if a manifest is invalid or CATALOG.md is out of date (for pull requests).

import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const addinsDir = join(repoRoot, 'addins');
const checkOnly = process.argv.includes('--check');

const REQUIRED = ['name', 'title', 'summary', 'category', 'authors', 'license', 'minBcVersion', 'target', 'interface'];
const REQUIRED_FILES = ['README.md', 'app.json', 'ControlAddIn/js/startup.js'];

const errors = [];
const entries = [];

for (const folder of readdirSync(addinsDir).sort()) {
    const dir = join(addinsDir, folder);
    if (!statSync(dir).isDirectory()) continue;

    const manifestPath = join(dir, 'addin.json');
    if (!existsSync(manifestPath)) {
        errors.push(`${folder}: addin.json missing`);
        continue;
    }

    let m;
    try {
        m = JSON.parse(readFileSync(manifestPath, 'utf8'));
    } catch (e) {
        errors.push(`${folder}: addin.json is not valid JSON (${e.message})`);
        continue;
    }

    for (const key of REQUIRED) {
        if (m[key] === undefined || m[key] === '') errors.push(`${folder}: "${key}" missing in addin.json`);
    }
    if (m.name && m.name !== folder) errors.push(`${folder}: "name" must equal the folder name`);
    for (const f of REQUIRED_FILES) {
        if (!existsSync(join(dir, f))) errors.push(`${folder}: ${f} missing`);
    }
    if (!readdirSync(join(dir, 'ControlAddIn')).some((f) => f.endsWith('.ControlAddIn.al'))) {
        errors.push(`${folder}: no *.ControlAddIn.al file in ControlAddIn/`);
    }

    entries.push({ folder, ...m });
}

const byCategory = {};
for (const e of entries) (byCategory[e.category] ??= []).push(e);

let md = '# Catalog\n\n';
md += '> Generated by `scripts/build-catalog.mjs` from the `addin.json` files. Do not edit by hand.\n\n';
md += `**${entries.length} add-ins**\n\n`;
for (const cat of Object.keys(byCategory).sort()) {
    md += `## ${cat}\n\n| Add-in | Description | External libs | Min. BC | Authors |\n|---|---|---|---|---|\n`;
    for (const e of byCategory[cat]) {
        const libs = (e.externalDependencies ?? []).length ? e.externalDependencies.join(', ') : 'none';
        const authors = (e.authors ?? []).map((a) => `@${a}`).join(', ');
        md += `| [${e.title}](addins/${e.folder}) | ${e.summary} | ${libs} | ${e.minBcVersion} | ${authors} |\n`;
    }
    md += '\n';
}

const json = JSON.stringify(entries, null, 2) + '\n';
const mdPath = join(repoRoot, 'CATALOG.md');
const jsonPath = join(repoRoot, 'catalog.json');

if (errors.length) {
    console.error('Manifest errors:\n- ' + errors.join('\n- '));
    process.exit(1);
}

if (checkOnly) {
    const current = existsSync(mdPath) ? readFileSync(mdPath, 'utf8') : '';
    if (current !== md) {
        console.error('CATALOG.md is out of date. Run: node scripts/build-catalog.mjs');
        process.exit(1);
    }
    console.log(`OK: ${entries.length} add-ins, catalog up to date.`);
} else {
    writeFileSync(mdPath, md);
    writeFileSync(jsonPath, json);
    console.log(`Wrote CATALOG.md and catalog.json (${entries.length} add-ins).`);
}
